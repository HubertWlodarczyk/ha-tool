def camel(s: str, upper: bool = False) -> str:
    parts = [p for p in s.replace("-", "_").split("_") if p]
    out = parts[0] + "".join(p.title() for p in parts[1:])
    return out[0].upper() + out[1:] if upper else out


def py_name(s: str) -> str:
    s = s.replace("-", "_")
    return s + "_" if keyword.iskeyword(s) else s


JAVA_KEYWORDS = {"new", "default", "switch", "case", "class", "int", "long", "boolean"}


def java_name(word: str, path: str = "") -> str:
    if word == "new":
        return "newBroadcast" if path.startswith("bcast") else "newItem"
    name = camel(word)
    return name + "_" if name in JAVA_KEYWORDS else name
