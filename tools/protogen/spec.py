def wire(c: dict) -> str:
    """Words of the command line; a target argument appears as {name}: 'broadcast {big} start'."""
    return c.get("wire", c["cmd"])


def targets(c: dict) -> list[str]:
    return [w[1:-1] for w in wire(c).split() if w.startswith("{")]


def optional_flags(c: dict) -> list[dict]:
    return [f for f in c.get("flags", []) if not f.get("required")]


def required_flags(c: dict) -> list[dict]:
    return [f for f in c.get("flags", []) if f.get("required")]


def required_args(c: dict) -> list[dict]:
    return [a for a in c.get("args", []) if not a.get("optional") and not a.get("list")]


def optional_args(c: dict) -> list[dict]:
    return [a for a in c.get("args", []) if a.get("optional") and not a.get("list")]


def list_arg(c: dict) -> dict | None:
    return next((a for a in c.get("args", []) if a.get("list")), None)


def notes(a: dict) -> list[str]:
    """Human readable constraints of an argument: values, range, unit, doc."""
    out = []
    if a.get("values"):
        out.append("|".join(a["values"]))
    if a.get("range"):
        out.append(f"{a['range'][0]}..{a['range'][1]}")
    if a.get("unit"):
        out.append(a["unit"])
    if a.get("doc"):
        out.append(a["doc"])
    return out


def reply_doc(c: dict) -> str:
    reply = c.get("reply", {})
    return "Reply: " + ", ".join(f"{k} ({v})" for k, v in reply.items()) if reply else ""


