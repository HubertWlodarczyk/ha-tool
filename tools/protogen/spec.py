def load(path: pathlib.Path) -> dict:
    return yaml.safe_load(path.read_text())


@dataclass
class Node:
    """A word of a command path: a command (cmd set), a group of commands, or both."""

    path: str
    cmd: dict | None = None
    children: dict[str, Node] = field(default_factory=dict)

    @property
    def groups(self) -> dict[str, Node]:
        return {w: n for w, n in self.children.items() if n.children}

    @property
    def commands(self) -> dict[str, dict]:
        return {w: n.cmd for w, n in self.children.items() if n.cmd is not None}

    @property
    def class_stem(self) -> str:
        """'bcast bis' -> 'BcastBis'"""
        return camel(self.path.replace(" ", "_"), upper=True)


def tree(spec: dict) -> Node:
    root = Node("")
    for c in spec["commands"]:
        node = root
        words = c["cmd"].split()
        for i, w in enumerate(words):
            node = node.children.setdefault(w, Node(" ".join(words[: i + 1])))
        node.cmd = c
    return root


